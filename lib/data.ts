const MIN = 60_000;

function bot(name: string, basket: BasketLine[], cutlery = false): Participant {
  return { userId: `bot-${name.toLowerCase()}`, name, isBot: true, basket, finalised: true, paid: false, cutlery };
}

function seedParty(
  restaurantId: string,
  pickupPointId: string,
  now: number,
  minsAgo: number,
  minsLeft: number,
  participants: Participant[],
): OrderRequest {
  return {
    id: `seed-${restaurantId}`,
    restaurantId,
    pickupPointId,
    hostId: participants[0].userId,
    createdAt: now - minsAgo * MIN,
    expiresAt: now + minsLeft * MIN,
    status: "open",
    participants,
    round: 1,
    removedUserIds: [],
    removedNames: [],
    attempt: 1,
    released: [],
  };
}

